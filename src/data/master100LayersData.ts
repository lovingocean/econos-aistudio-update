export const getLayerByNumber = (num: number): MasterLayerSpec | undefined => {
  return MASTER_100_LAYERS.find(l => l.layerNumber === num);
};

export const getLayerById = (id: string): MasterLayerSpec | undefined => {
  // Check exact ID
  let found = MASTER_100_LAYERS.find(l => l.id === id);
  if (found) return found;

  // Check numerical match like LAYER_62 or 62
  const numMatch = id.match(/\d+/);
  if (numMatch) {
    const n = parseInt(numMatch[0], 10);
    return MASTER_100_LAYERS.find(l => l.layerNumber === n);
  }
  return undefined;
};
